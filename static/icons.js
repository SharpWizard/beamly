// animated number
window.countTo = function (el, val, fmt) {
  const from = el._v == null ? 0 : el._v;
  if (from === val && el._v != null) return;
  const grew = el._v != null && val > from;
  el._v = val;
  cancelAnimationFrame(el._raf);
  const t0 = performance.now(), dur = 750;
  const step = function (now) {
    const p = Math.min(1, (now - t0) / dur), k = 1 - Math.pow(1 - p, 3), v = from + (val - from) * k;
    el.textContent = fmt ? fmt(v) : Math.round(v);
    if (p < 1) el._raf = requestAnimationFrame(step);
  };
  el._raf = requestAnimationFrame(step);
  if (grew) { el.classList.remove('bump'); void el.offsetWidth; el.classList.add('bump'); }
};

// keyed list renderer: only touches rows that changed, animates enter / leave
window.keyed = function (box, list, keyFn, htmlFn, emptyHtml) {
  if (!list.length) {
    if (box._mode !== 'empty') { box.innerHTML = emptyHtml; box._mode = 'empty'; }
    return;
  }
  if (box._mode !== 'list') { box.innerHTML = ''; box._first = box._mode === undefined; box._mode = 'list'; }
  const first = box._first; box._first = false;
  const have = new Map();
  [...box.children].forEach(function (c) { if (c.dataset.k != null && !c.classList.contains('leaving')) have.set(c.dataset.k, c); });
  const want = new Set();
  let prev = null;
  list.forEach(function (it, i) {
    const k = String(keyFn(it)); want.add(k);
    const html = htmlFn(it, i).trim();
    let el = have.get(k);
    if (!el || el._html !== html) {
      const t = document.createElement('div'); t.innerHTML = html;
      const n = t.firstElementChild; n.dataset.k = k; n._html = html;
      if (!el) { n.classList.add(first ? 'rise' : 'enter'); n.style.setProperty('--i', i); }
      if (el) el.replaceWith(n);
      el = n;
    }
    const ref = prev ? prev.nextSibling : box.firstChild;
    if (el !== ref) box.insertBefore(el, ref);
    prev = el;
  });
  have.forEach(function (el, k) {
    if (want.has(k)) return;
    el.style.height = el.offsetHeight + 'px'; void el.offsetHeight;
    el.classList.add('leaving');
    setTimeout(function () { el.remove(); }, 340);
  });
};

